# 2. 计算相对Gap（%）
def calculate_relative_gap(df, baseline_col='HPRL'):
    """计算各算法相对于基准的Gap百分比"""
    base = df[baseline_col]
    gap_df = pd.DataFrame()

    for col in df.columns:
        if col == baseline_col:
            gap_df[col] = np.zeros(len(df))  # 基准自身Gap为0%
        else:
            gap_df[col] = (df[col] / base - 1) * 100  # Gap计算公式

    return gap_df

gap_df = calculate_relative_gap(df)
