    # 判定：如果 p < 0.05 则认为显著优于对方 (+)
    is_significant = "+" if p_value < 0.05 else "≈"
    results_for_table.append((name, p_value, is_significant))

    print(f"{my_alg} vs {name:<14} | {p_value:<15.4e} | {is_significant}")

