results_for_table = []

# 2. 循环计算
for name, results in data.items():
    if name == my_alg:
        continue

    baseline_results = np.array(results)

    # 长度检查，防止数据录入错误
    if len(baseline_results) != n_instances:
        print(f"警告: {name} 的数据长度 ({len(baseline_results)}) 与 {my_alg} 不符！")
        continue

    # 执行 Wilcoxon 符号秩检验
    # alternative='less' 意味着检验: DCFRL 是否显著“小于”基准算法 (适用于 Makespan 等越小越好的指标)
