# =====================================================
# 2. 根据点数生成 normalized training progress
# =====================================================

def generate_progress(num_points):

    return np.linspace(
        100 / num_points,
        100,
        num_points
    )

MDGRL_x = generate_progress(
    len(MDGRL_mean))

HAGRL_x = generate_progress(
    len(HAGRL_mean))

THGRL_x = generate_progress(
    len(THGRL_mean))

Proposed_x = generate_progress(
    len(Proposed_mean))

# =====================================================
# 3. 绘图函数
# =====================================================

def plot_curve(
        x,
        mean,
        std,
        label
):

    plt.plot(
        x,
        mean,
        linewidth=2,
        label=label
    )

    plt.fill_between(
        x,
        mean - std,
        mean + std,
        alpha=0.2
    )

# =====================================================
# 4. 绘制收敛曲线
# =====================================================
plt.figure(figsize=(10,6))

plot_curve(MDGRL_x, MDGRL_mean, MDGRL_std,"MDGRL")
plot_curve(HAGRL_x, HAGRL_mean, HAGRL_std,"HAGRL")
plot_curve(THGRL_x, THGRL_mean, THGRL_std,"THGRL")
plot_curve(Proposed_x, Proposed_mean, Proposed_std,"HPRL")

